const assert = require('node:assert/strict');
const crypto = require('node:crypto');

module.exports = async function verifyAdministration({ call, idToken, centerId, db, hash }) {
  const base = `/centers/${centerId}`;
  const withAudit = (input, operationId = crypto.randomUUID()) => ({ ...input, reason: 'Gestión del equipo sintético del centro', operationId });
  assert.equal((await call(`${base}/members`, idToken)).response.status, 403);
  assert.equal((await call(`${base}/members`, idToken, 'POST', withAudit({ email: 'sinpermiso@hospital.cl', roles: ['nurse'] }))).response.status, 403);
  const initialCatalog = await call(`${base}/nursing-catalog`, idToken);
  assert.equal(initialCatalog.response.status, 200);
  assert(initialCatalog.payload.catalog.options.cleaning.includes('Suero fisiológico'));
  assert.equal((await call(`${base}/nursing-catalog`, idToken, 'PUT', { revision: 0, options: initialCatalog.payload.catalog.options })).response.status, 403);
  await db.doc(`memberships/${centerId}_${hash}`).update({ roles: ['doctor', 'nurse', 'auditor', 'center_admin'] });
  const options = { ...initialCatalog.payload.catalog.options, cleaning: ['Limpieza de prueba'], secondaryDressings: [] };
  assert.equal((await call(`${base}/nursing-catalog`, idToken, 'PUT', { revision: 0, options: { ...options, debridement: ['Cortante conservador'] } })).response.status, 400);
  const savedCatalog = await call(`${base}/nursing-catalog`, idToken, 'PUT', { revision: 0, options });
  assert.equal(savedCatalog.response.status, 200); assert.equal(savedCatalog.payload.catalog.revision, 1);
  assert.deepEqual((await call(`${base}/nursing-catalog`, idToken)).payload.catalog.options.cleaning, ['Limpieza de prueba']);
  assert.equal((await call(`${base}/nursing-catalog`, idToken, 'PUT', { revision: 0, options })).response.status, 409);
  const otherCenter = 'otro-centro-catalogo';
  await db.doc(`centers/${otherCenter}`).set({ status: 'active', name: 'Otro centro' });
  assert.equal((await call(`/centers/${otherCenter}/nursing-catalog`, idToken)).response.status, 403);
  assert.equal((await call(`/centers/${otherCenter}/nursing-catalog`, idToken, 'PUT', { revision: 0, options })).response.status, 403);
  assert.equal((await call(`${base}/settings`, idToken, 'PUT', { name: '   ' })).response.status, 400);
  await db.doc(`centers/${centerId}`).update({ address: 'Dirección conservada' });
  const settings = await call(`${base}/settings`, idToken, 'PUT', { name: 'Nombre actualizado' });
  assert.equal(settings.response.status, 200); assert.equal(settings.payload.center.address, 'Dirección conservada');
  assert.equal((await call(`${base}/members`, idToken, 'POST', withAudit({ email: 'incorrecto', roles: ['nurse'] }))).response.status, 400);
  assert.equal((await call(`${base}/members`, idToken, 'POST', withAudit({ email: 'nuevo@hospital.cl', roles: ['nurse', 'platform_admin'] }))).response.status, 400);
  const noReason = await call(`${base}/members`, idToken, 'POST', { email: 'sinmotivo@hospital.cl', roles: ['nurse'], operationId: crypto.randomUUID() });
  assert.equal(noReason.response.status, 400);
  assert.match(noReason.payload.error, /motivo/i);
  const auditConflictId = crypto.randomUUID();
  await db.doc(`centers/${centerId}/auditLogs/${auditConflictId}`).set({ action: 'unrelated', result: 'succeeded' });
  const blocked = await call(`${base}/members`, idToken, 'POST', withAudit({ email: 'auditfail@hospital.cl', roles: ['nurse'] }, auditConflictId));
  assert.equal(blocked.response.status, 409);
  assert.match(blocked.payload.error, /operación/i);
  const createdInput = withAudit({ email: 'NUEVO@hospital.cl', displayName: 'Nuevo integrante', roles: ['nurse'] });
  const created = await call(`${base}/members`, idToken, 'POST', createdInput);
  assert.equal(created.response.status, 201); assert.equal(created.payload.member.status, 'invited');
  const replayed = await call(`${base}/members`, idToken, 'POST', createdInput);
  assert.equal(replayed.response.status, 201); assert.equal(replayed.payload.replayed, true);
  const memberId = created.payload.member.id;
  const memberAudit = (await db.doc(`centers/${centerId}/auditLogs/${createdInput.operationId}`).get()).data();
  assert.equal(memberAudit.actorUid, (await db.doc(`memberships/${centerId}_${hash}`).get()).data().uid);
  assert.equal(memberAudit.centerId, centerId);
  assert.equal(memberAudit.action, 'member.invited');
  assert.equal(memberAudit.reason, createdInput.reason);
  assert.equal(memberAudit.result, 'succeeded');
  assert.equal(memberAudit.requestId, created.response.headers.get('x-request-id'));
  assert.equal(memberAudit.httpStatus, 201);
  assert.equal(memberAudit.before, null);
  assert.deepEqual(memberAudit.after, { roles: ['nurse'], status: 'invited' });
  assert.equal(JSON.stringify(memberAudit).includes('Paciente Sintético'), false);
  assert.equal((await db.doc(`memberships/${centerId}_${crypto.createHash('sha256').update('auditfail@hospital.cl').digest('hex')}`).get()).exists, false, 'Auditoría en conflicto no puede crear membresía');
  const duplicate = await call(`${base}/members`, idToken, 'POST', withAudit({ email: 'nuevo@hospital.cl', roles: ['center_admin'] }));
  assert.equal(duplicate.response.status, 409);
  assert.deepEqual((await db.doc(`memberships/${memberId}`).get()).data().roles, ['nurse']);
  assert.equal((await call(`${base}/members/${memberId}`, idToken, 'PUT', { roles: ['doctor'], operationId: crypto.randomUUID() })).response.status, 400);
  assert.equal((await call(`${base}/members/${memberId}`, idToken, 'PUT', withAudit({ roles: [] }))).response.status, 400);
  const editedInput = withAudit({ roles: ['nurse', 'doctor'] });
  const edited = await call(`${base}/members/${memberId}`, idToken, 'PUT', editedInput);
  assert.equal(edited.response.status, 200); assert.deepEqual(edited.payload.member.roles, ['nurse', 'doctor']);
  const editAudit = (await db.doc(`centers/${centerId}/auditLogs/${editedInput.operationId}`).get()).data();
  assert.deepEqual(editAudit.before, { roles: ['nurse'], status: 'invited' });
  assert.deepEqual(editAudit.after, { roles: ['nurse', 'doctor'], status: 'invited' });
  const disabledInput = withAudit({ status: 'disabled' });
  assert.equal((await call(`${base}/members/${memberId}`, idToken, 'PUT', disabledInput)).payload.member.status, 'disabled');
  assert.deepEqual((await db.doc(`centers/${centerId}/auditLogs/${disabledInput.operationId}`).get()).data().after, { roles: ['nurse', 'doctor'], status: 'disabled' });
  const reactivatedInput = withAudit({ status: 'active' });
  assert.equal((await call(`${base}/members/${memberId}`, idToken, 'PUT', reactivatedInput)).payload.member.status, 'invited');
  assert.deepEqual((await db.doc(`centers/${centerId}/auditLogs/${reactivatedInput.operationId}`).get()).data().before, { roles: ['nurse', 'doctor'], status: 'disabled' });
  assert.equal((await call(`${base}/members/${memberId}`, idToken, 'PUT', withAudit({ status: 'invited' }))).response.status, 400);
  assert.equal((await call(`${base}/members/${centerId}_${hash}`, idToken, 'PUT', withAudit({ status: 'disabled' }))).response.status, 409);
  assert.equal((await call(`${base}/members/${centerId}_${hash}`, idToken, 'PUT', withAudit({ roles: ['doctor'] }))).response.status, 409);
  const foreignId = 'otro-centro_miembro';
  await db.doc(`memberships/${foreignId}`).set({ centerId: 'otro-centro', roles: ['nurse'], status: 'active' });
  assert.equal((await call(`${base}/members/${foreignId}`, idToken, 'PUT', withAudit({ roles: ['center_admin'] }))).response.status, 404);
  console.log('Administración: invitaciones, duplicados, perfiles, aislamiento y continuidad verificados.');
};
